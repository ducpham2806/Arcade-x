import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {createClient} from '@supabase/supabase-js';
import fs from 'node:fs';
const bundled=await build({entryPoints:['src/services/authRedirect.ts'],bundle:true,write:false,format:'esm'});
const {buildAuthRedirect}=await import('data:text/javascript;base64,'+Buffer.from(bundled.outputFiles[0].text).toString('base64'));
assert.equal(buildAuthRedirect('content://downloads/launcher.html'),undefined);
assert.equal(buildAuthRedirect('file:///phone/launcher.html',true),undefined);
assert.equal(buildAuthRedirect('https://game.example/arcade/?old=1#old'), 'https://game.example/arcade/?auth=confirmation');
assert.equal(buildAuthRedirect('file:///launcher.html',true,'https://game.example/arcade/'), 'https://game.example/arcade/?auth=recovery');
const config=JSON.parse(fs.readFileSync('src/config/public-backend.json'));
assert.equal(config.url,'https://whjatkhhupeqfngakmee.supabase.co');
assert.ok(config.publishableKey.startsWith('sb_publishable_'));
const requests=[];
const sdk=createClient(config.url,config.publishableKey,{auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false},global:{fetch:async(url,options)=>{
 requests.push({url:String(url),body:JSON.parse(options.body)});
 return new Response(JSON.stringify({code:'invalid_credentials',msg:'Test response'}),{status:400,headers:{'Content-Type':'application/json'}});
}}});
await sdk.auth.signUp({email:'test@example.com',password:'ExamplePass123!',options:{emailRedirectTo:buildAuthRedirect('content://launcher.html')}});
await sdk.auth.signInWithPassword({email:'test@example.com',password:'ExamplePass123!'});
assert.ok(requests[0].url.endsWith('/auth/v1/signup'));
assert.ok(requests[1].url.endsWith('/auth/v1/token?grant_type=password'));
assert.equal(requests[0].body.email,'test@example.com');
assert.equal(requests[1].body.password,'ExamplePass123!');
assert.ok(!requests[0].url.includes('null'));
const preview=fs.readFileSync('scripts/launcher-preview.mjs','utf8');
assert.ok(preview.includes("loadEnv('production',root,'VITE_')"));
assert.ok(preview.includes("'import.meta.env':JSON.stringify(reviewEnv)"));
console.log('PASS: portable callback URLs, public backend config, signup/login SDK requests, preview environment preservation. No account created or email sent.');
