/**
 * Returns dynamic Hall of Fame entries comparing player's local high scores.
 * If player score >= recordScore, player is crowned as the record holder!
 */
export function getResolvedHallOfFame(profile: PlayerProfile): HallOfFameEntry[] {
  return BASE_HALL_OF_FAME_DATA.map((base) => {
    const userScore = profile.stats.highScores[base.gameId] || 0;
    const isUserBeating = userScore > base.recordScore;

    if (isUserBeating) {
      return {
        ...base,
        holderName: profile.username,
        holderAvatar: profile.avatar || '👑',
        holderTitle: profile.currentTitle || 'Tân Kỷ Lục Gia',
        recordScore: userScore,
        recordDate: 'Hôm Nay (Mới)',
        specialFeat: `Đã phá vỡ kỷ lục cũ ${base.recordScore.toLocaleString()} ${base.scoreUnit || 'pts'}!`,
        isUserHolder: true,
      };
    }

    return {
      ...base,
      isUserHolder: false,
    };
  });
}
