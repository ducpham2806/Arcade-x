"""Pack reviewed imagegen props; processed PNGs are the alpha source of truth."""
from pathlib import Path
from PIL import Image
import hashlib,json,base64
root=Path(__file__).resolve().parent.parent
art=root/'art/snake-legend/props-a2'
canvas=Image.new('RGBA',(512,512))
frames={}
for kind,size,y,names in [('exit',192,2,['exit_closed','exit_ready']),('switch',128,198,['switch_off','switch_on'])]:
 for i,name in enumerate(names):
  image=Image.open(art/f'{kind}-processed/sheet-{i+1}.png').convert('RGBA')
  assert image.size==(size,size)
  x=2+i*(size+4)
  canvas.alpha_composite(image,(x,y))
  frames[name]={'frame':{'x':x,'y':y,'w':size,'h':size},'pivot':{'x':.5,'y':.5}}
canvas.save(art/'story-props.webp',lossless=True,method=6)
data=(art/'story-props.webp').read_bytes()
assert len(data)<=180*1024
atlas={'frames':frames,'meta':{'size':{'w':512,'h':512},'decodedBytes':512*512*4,'art_source':'host_image','route':'imagegen built-in','model':None,'estimateUsd':None,'status':'A2_interactive_props_candidate'}}
(art/'atlas.json').write_text(json.dumps(atlas,indent=2)+'\n')
module='// Generated by scripts/build-snake-props.py from reviewed, native-alpha imagegen props.\n'
module+='export const storyPropAssets='+json.dumps({'image':'data:image/webp;base64,'+base64.b64encode(data).decode(),'atlas':atlas},separators=(',',':'))+' as const;\n'
module+='export type StoryPropId=keyof typeof storyPropAssets.atlas.frames;\n'
(root/'src/games/snake-legend/src/story-prop-assets.ts').write_text(module)
# Visual review aid at actual logical sizes, on the two arena contrast backgrounds.
review=Image.new('RGB',(512,250),'#dbe9be')
from PIL import ImageDraw
ImageDraw.Draw(review).rectangle((0,125,512,250),fill='#183e37')
for row in range(2):
 for col,(kind,source_size,unused,names) in enumerate([('exit',192,0,['exit_closed','exit_ready']),('switch',128,0,['switch_off','switch_on'])]):
  for i,name in enumerate(names):
   frame=frames[name]['frame'];im=canvas.crop((frame['x'],frame['y'],frame['x']+source_size,frame['y']+source_size))
   for scale_index,target_size in enumerate([32,48]):
    # Pillow RGBa resampling avoids dark fringes; source already keeps its shared registration.
    im_small=im.convert('RGBa').resize((target_size,target_size),Image.Resampling.LANCZOS).convert('RGBA')
    review.paste(im_small,(col*256+i*112+scale_index*46+12,row*125+32),im_small)
review.save(art/'game-size-review.png')
print(json.dumps({'status':'PASS','bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),'decodedBytes':atlas['meta']['decodedBytes'],'frames':list(frames)}))
