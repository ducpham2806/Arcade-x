"""Original procedural celesta/pad loops for Arcade-x. No sampled recordings."""
from pathlib import Path
import numpy as np, wave, subprocess, tempfile, json
RATE=44100
OUT=Path('public/blossom/audio/music');OUT.mkdir(parents=True,exist_ok=True)
scales=[[0,2,4,7,9],[0,2,4,5,7,9],[0,2,4,7,9],[0,2,5,7,9],[0,3,5,7,10],[0,2,4,7,9],[0,2,3,7,10],[0,2,4,7,9],[0,3,5,7,10],[0,2,4,7,9]]
metadata=[]
for chapter in range(1,11):
    bpm=[92,100,96,88,84,98,80,76,86,90][chapter-1];beat=60/bpm;length=32*beat
    data=np.zeros((round(RATE*length),2));scale=scales[chapter-1];root=[60,62,65,67,60,64,62,65,59,60][chapter-1]
    motif=[0,2,1,3,2,4,3,1]
    def tone(start,seconds,midi,volume,pan,soft=False):
        n=round(seconds*RATE);t=np.arange(n)/RATE;f=440*2**((midi-69)/12)
        env=(1-np.exp(-t/(.08 if soft else .012)))*np.exp(-t/(1.1 if soft else .32));env*=np.minimum(1,(seconds-t)/.08)
        sound=(np.sin(2*np.pi*f*t)+(.16 if soft else .28)*np.sin(4*np.pi*f*t)+.08*np.sin(6*np.pi*f*t))*env*volume
        offset=round(start*RATE);channels=[np.sqrt((1-pan)/2),np.sqrt((1+pan)/2)]
        # Wrap the decay into the next loop, so the boundary stays continuous.
        for ch in range(2):
            end=min(len(data)-offset,n);data[offset:offset+end,ch]+=sound[:end]*channels[ch]
            if end<n:data[:n-end,ch]+=sound[end:]*channels[ch]
    for bar in range(8):
        chord=[0,3,4,0][bar%4]
        for degree in [0,2,4]:tone(bar*4*beat,4*beat,root-12+scale[(chord+degree)%len(scale)],.075,0,True)
        for step in range(4):
            degree=motif[(bar*4+step+chapter)%8]%len(scale)
            tone((bar*4+step)*beat,beat*2,root+12+scale[degree],.12,(-.25 if step%2 else .25))
    peak=np.max(np.abs(data));data*=.7/max(.7,peak)
    with tempfile.TemporaryDirectory() as tmp:
        wav=Path(tmp)/'loop.wav'
        with wave.open(str(wav),'wb') as f:f.setnchannels(2);f.setsampwidth(2);f.setframerate(RATE);f.writeframes((data*32767).astype('<i2').tobytes())
        target=OUT/f'chapter-{chapter:02}.ogg'
        subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-i',str(wav),'-c:a','libvorbis','-q:a','3',str(target)],check=True)
    metadata.append({'chapter':chapter,'bpm':bpm,'seconds':round(length,3),'file':target.name,'original':True})
(OUT/'TRACKS.json').write_text(json.dumps(metadata,indent=2)+'\n')
(OUT/'LICENSE.txt').write_text('Original procedural compositions and synthesis generated by scripts/blossom-music.py for Arcade-x. No third-party samples. Dedicated to the public domain under CC0 1.0.\n')
print(f'Created {len(metadata)} original loops; {sum(p.stat().st_size for p in OUT.glob("*.ogg"))} bytes.')
