"""Offline, deterministic air/modal SFX for Snake R01; no external audio or model."""
from pathlib import Path
import wave,json,hashlib,base64
import numpy as np
from scipy.signal import butter,sosfilt
root=Path(__file__).resolve().parent.parent
out=root/'art/snake-legend/audio-r02';out.mkdir(exist_ok=True)
rate=44100;rng=np.random.default_rng(2806)
def lowpass(x,hz=4800):return sosfilt(butter(3,hz,fs=rate,output='sos'),x)
def air(n,lo,hi):return sosfilt(butter(2,[lo,hi],fs=rate,btype='bandpass',output='sos'),rng.normal(size=n))
def envelope(t,length,attack=.012):
 return np.minimum(1,t/attack)**2*np.minimum(1,(length-t)/.035)**2
def modal(t,freqs,weights,decays):
 return sum(w*np.sin(2*np.pi*f*t)*np.exp(-t/d) for f,w,d in zip(freqs,weights,decays))
def finish(x,length,peak):
 t=np.arange(len(x))/rate;x=lowpass(x)*envelope(t,length)
 x=x/max(np.max(np.abs(x)),1e-9)*peak;x[0]=x[-1]=0
 return np.round(x*32767).astype('<i2')
length=.30;t=np.arange(round(length*rate))/rate
whoosh=air(len(t),320,3900)*(np.sin(np.pi*t/length)**1.8)
whoosh+=.10*modal(t,[180,283,467],[1,.38,.16],[.045,.03,.018])
dash=finish(whoosh,length,.18)
length=.62;t=np.arange(round(length*rate))/rate
bell=modal(t,[392,789.3,1111.7,1642],[1,.30,.18,.06],[.24,.18,.12,.09])
delay=.095;u=np.maximum(0,t-delay);bell+=(t>=delay)*.42*modal(u,[587.3,1179.9,1660],[1,.22,.09],[.23,.16,.1])*np.minimum(1,u/.012)**2
bell+=.018*air(len(t),900,4300)*np.exp(-t/.10)
weak=finish(bell,length,.19)
length=.82;t=np.arange(round(length*rate))/rate
wood=modal(t,[174.6,289.1,464.8,699.2],[1,.52,.24,.12],[.16,.13,.09,.06])
u=np.maximum(0,t-.16);wood+=(t>=.16)*.5*modal(u,[261.6,435.3,698.4],[1,.36,.10],[.23,.14,.08])*np.minimum(1,u/.012)**2
wood+=.025*air(len(t),240,2400)*np.exp(-t/.28)
phase=finish(wood,length,.18)
files={'sfx_dash_air':dash,'sfx_boss_weak_open':weak,'sfx_boss_phase':phase}
meta=[];bank={}
for name,samples in files.items():
 path=out/(name+'.wav')
 with wave.open(str(path),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(rate);w.writeframes(samples.tobytes())
 data=path.read_bytes();bank[name]=base64.b64encode(data).decode();a=samples.astype(float)/32768
 meta.append({'id':name,'path':path.name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),'seconds':len(a)/rate,'rate':rate,'channels':1,'bits':16,'peak':float(abs(a).max()),'rms':float(np.sqrt(np.mean(a*a))),'firstSample':int(samples[0]),'lastSample':int(samples[-1])})
assert sum(x['bytes'] for x in meta)<=180*1024
assert all(x['peak']<=.20 and x['seconds']<=1 for x in meta)
(out/'manifest.json').write_text(json.dumps({'route':'offline procedural audio','method':'filtered noise and damped inharmonic modal resonances','seed':2806,'model':None,'files':meta},indent=2)+'\n')
(root/'src/games/snake-legend/src/audio-feedback-assets.ts').write_text('// Generated by scripts/build-snake-audio.py; offline air/modal synthesis, no AI model.\nexport const feedbackAudioAssets='+json.dumps(bank,separators=(',',':'))+' as const;\n')
# A concise listening reel: Dash, weak opening, phase transition, separated by silence.
reel=np.concatenate([dash,np.zeros(round(.35*rate),dtype='<i2'),weak,np.zeros(round(.35*rate),dtype='<i2'),phase])
with wave.open(str(out/'listening-reel.wav'),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(rate);w.writeframes(reel.tobytes())
print(json.dumps({'status':'PASS','files':meta,'totalBytes':sum(x['bytes'] for x in meta),'reelSeconds':len(reel)/rate}))
