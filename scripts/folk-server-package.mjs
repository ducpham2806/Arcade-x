// Bundle the Folk Edge Function using the same rules and protocol as the browser.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const target = 'supabase/functions/folk-duel-room/entrypoint.js';
const { outputFiles } = await build({
  entryPoints: ['supabase/functions/folk-duel-room/index.ts'],
  bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022',
  banner: { js: '// Generated by npm run prepare:folk-server. Edit index.ts, engine.ts or server.ts and regenerate.' },
});
const text = outputFiles[0].text;
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(target, 'utf8'), text, 'Folk Edge bundle is stale. Run npm run prepare:folk-server.');
} else writeFileSync(target, text);
console.log('Folk Edge bundle matches shared sources.');
